# IN-MEMORY AI TOKEN TRACKER FOR UI / API
# ---------------------------------------------------------------------------

class AITokenTracker:
    def __init__(self, max_history: int = 100):
        self.max_history = max_history
        self.history = deque(maxlen=max_history)
        self.total_prompt_tokens = 0
        self.total_completion_tokens = 0
        self.total_requests = 0
        self.model_stats: Dict[str, Dict[str, Any]] = {}
        self.start_time = time.time()

    @staticmethod
    def estimate_tokens(text: Optional[str]) -> int:
        """
        Robust fallback token estimation for models that don't return exact token counts.
        Uses empirical character + whitespace heuristic:
        - 1 token ≈ 3.8 - 4.0 characters of English/Code
        - At least 1 token if non-empty
        """
        if not text:
            return 0
        # Count words and character length
        words = len(text.split())
        chars = len(text)
        # Average between character-based (chars / 3.8) and word-based (words * 1.3)
        token_estimate = max(1, int(math.ceil((chars / 3.8 + words * 1.3) / 2.0)))
        return token_estimate

    def record_inference(
        self,
        model: str,
        engine: str,
        prompt_tokens: int,
        completion_tokens: int,
        duration_s: float,
        success: bool = True,
        call_type: str = "chat",
        prompt_snippet: str = "",
        response_snippet: str = ""
    ) -> Dict[str, Any]:
        """
        Records an AI inference execution into Prometheus metrics and memory log.
        """
        total_tokens = prompt_tokens + completion_tokens
        status_str = "success" if success else "error"
        tps = round(completion_tokens / max(duration_s, 0.001), 2)

        # Update Prometheus metrics
        AI_TOKENS_PROMPT.labels(model=model, engine=engine, call_type=call_type).inc(prompt_tokens)
        AI_TOKENS_COMPLETION.labels(model=model, engine=engine, call_type=call_type).inc(completion_tokens)
        AI_TOKENS_TOTAL.labels(model=model, engine=engine, call_type=call_type).inc(total_tokens)
        AI_TOKEN_RATE.labels(model=model, engine=engine).set(tps)
        AI_INFERENCE_DURATION.labels(model=model, engine=engine, status=status_str).observe(duration_s)
        AI_REQUESTS_TOTAL.labels(model=model, engine=engine, status=status_str, call_type=call_type).inc(1)

        # Update in-memory tracker stats
        self.total_prompt_tokens += prompt_tokens
        self.total_completion_tokens += completion_tokens
        self.total_requests += 1

        if model not in self.model_stats:
            self.model_stats[model] = {
                "prompt_tokens": 0,
                "completion_tokens": 0,
                "total_tokens": 0,
                "requests": 0,
                "total_duration_s": 0.0,
                "avg_tps": 0.0
            }

        m = self.model_stats[model]
        m["prompt_tokens"] += prompt_tokens
        m["completion_tokens"] += completion_tokens
        m["total_tokens"] += total_tokens
        m["requests"] += 1
        m["total_duration_s"] += duration_s
        m["avg_tps"] = round(m["completion_tokens"] / max(m["total_duration_s"], 0.001), 2)

        record = {
            "timestamp": time.time(),
            "iso_time": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "model": model,
            "engine": engine,
            "call_type": call_type,
            "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens,
            "total_tokens": total_tokens,
            "duration_s": round(duration_s, 3),
            "tokens_per_sec": tps,
            "success": success,
            "prompt_preview": prompt_snippet[:100] + ("..." if len(prompt_snippet) > 100 else ""),
            "response_preview": response_snippet[:120] + ("..." if len(response_snippet) > 120 else "")
        }
        self.history.appendleft(record)
        return record

    def get_summary(self) -> Dict[str, Any]:
        """
        Returns JSON-formatted summary of all AI token analytics.
        """
        uptime_s = time.time() - self.start_time
        total_tokens = self.total_prompt_tokens + self.total_completion_tokens
        overall_tps = round(self.total_completion_tokens / max(uptime_s, 1), 2)

        return {
            "total_tokens": total_tokens,
            "prompt_tokens": self.total_prompt_tokens,
            "completion_tokens": self.total_completion_tokens,
            "total_requests": self.total_requests,
            "tokens_per_second": overall_tps,
            "uptime_seconds": round(uptime_s, 1),
            "models": self.model_stats,
            "recent_events": list(self.history)[:30]
        }


