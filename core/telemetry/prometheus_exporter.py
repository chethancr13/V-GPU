# 5. PLATFORM METRICS REFRESH HOOK (Invoked on /metrics scrape)
# ---------------------------------------------------------------------------

def refresh_platform_metrics() -> None:
    """
    Reads the latest live snapshot from core/chatbot/metrics_collector.py
    and synchronizes all Prometheus gauges with actual hardware / simulation state.
    """
    try:
        from core.chatbot.metrics_collector import get_live_snapshot
        snapshot = get_live_snapshot()

        # Update Physical GPUs
        for gpu in snapshot.get("physical_gpus", []):
            gid = str(gpu.get("gpu_id", 0))
            PHYSICAL_GPU_UTIL.labels(gpu_id=gid).set(gpu.get("utilization_pct", 0.0))
            PHYSICAL_GPU_MEM_USED.labels(gpu_id=gid).set(gpu.get("memory_used_mb", 0.0))
            PHYSICAL_GPU_MEM_TOTAL.labels(gpu_id=gid).set(gpu.get("memory_total_mb", 0.0))
            PHYSICAL_GPU_TEMP.labels(gpu_id=gid).set(gpu.get("temperature_c", 0.0))
            PHYSICAL_GPU_POWER.labels(gpu_id=gid).set(gpu.get("power_draw_w", 0.0))
            PHYSICAL_GPU_CLOCK.labels(gpu_id=gid).set(gpu.get("clock_speed_mhz", 0.0))

        # Update vGPU Instances
        vgpu_list = snapshot.get("vgpu_instances", [])
        VGPU_INSTANCES_COUNT.set(len(vgpu_list))
        total_allocated_vram = sum(inst.get("vram_limit_mb", 0) for inst in vgpu_list)
        VGPU_ALLOCATED_VRAM.set(total_allocated_vram)

        # Update Scheduler State
        sch = snapshot.get("scheduler", {})
        SCHEDULER_JOBS_ACTIVE.set(sch.get("active_jobs", 0))
        SCHEDULER_JOBS_PENDING.set(sch.get("pending_jobs", 0))
        SCHEDULER_JOBS_COMPLETED.set(sch.get("completed_jobs", 0))
        SCHEDULER_AVG_WAIT_TIME.set(sch.get("avg_wait_time_s", 0.0))
        SCHEDULER_THROUGHPUT.set(sch.get("avg_throughput", 0.0))

        # Update Water & Power Telemetry
        env = snapshot.get("water_environmental", {})
        if env:
            SERVER_POWER_KW.set(env.get("cluster_power_kw", 0.0))
            WATER_USAGE_EFFECTIVENESS.set(env.get("effective_wue", 0.0))
            WATER_CONSUMPTION_HOURLY.set(env.get("water_consumption_l_per_hr", 0.0))
            CHILLER_FLOW_RATE.set(env.get("chiller_flow_rate_l_per_min", 0.0))
            EVAPORATIVE_LOSS.set(env.get("evaporative_loss_l_per_hr", 0.0))
            COOLANT_RECIRCULATED.set(env.get("water_recirculated_l_per_hr", 0.0))

        # Update Multi-Tier Cache Metrics
        try:
            from core.cache.tier_cache import system_cache
            c_stats = system_cache.get_stats()
            CACHE_SIZE_ITEMS.set(c_stats["size"])
            CACHE_HIT_RATIO.set(c_stats["hit_ratio_pct"])
        except Exception:
            pass

        # Update Asynchronous Task Queue Metrics
        try:
            from core.queue.async_queue import async_task_queue
            q_stats = async_task_queue.get_stats()
            ASYNC_QUEUE_PENDING.set(q_stats["pending_in_queue"])
            ASYNC_QUEUE_ACTIVE.set(q_stats["active_executing"])
            ASYNC_QUEUE_COMPLETED.set(q_stats["total_completed"])
            ASYNC_QUEUE_DLQ_SIZE.set(q_stats["dlq_size"])
        except Exception:
            pass

        # Update Security Firewall Metrics
        try:
            from core.security.security_middleware import rate_limiter
            SECURITY_BLOCKED_IPS.set(len(rate_limiter.blocked_ips))
        except Exception:
            pass

    except Exception as e:
        print(f"[Prometheus Exporter] Error refreshing platform metrics: {e}")


